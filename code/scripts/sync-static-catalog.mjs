import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const codeRoot = path.resolve(scriptDir, "..");
const repoRoot = path.resolve(codeRoot, "..");
const fixturesDir = path.join(repoRoot, "fixtures");
const outputFile = path.join(codeRoot, "src", "data", "catalog.generated.ts");

async function readJson(name) {
	const filePath = path.join(fixturesDir, name);
	const contents = await fs.readFile(filePath, "utf8");
	return JSON.parse(contents);
}

const [artworkFixtures, collectionFixtures, productFixtures, homepageSlugs] = await Promise.all([
	readJson("artworks.json"),
	readJson("collections.json"),
	readJson("products.json"),
	readJson("homepage.json"),
]);

const publishedCollections = collectionFixtures
	.filter((collection) => collection.publishedAt)
	.map((collection) => ({
		name: collection.name,
		slug: collection.slug,
		description: collection.description ?? null,
		publishedAt: collection.publishedAt,
		locale: collection.locale ?? "en",
	}));

const collectionsBySlug = new Map(
	publishedCollections.map((collection) => [collection.slug, collection]),
);

const artworks = artworkFixtures
	.filter((artwork) => artwork.publishedAt)
	.map((artwork) => {
		const images = Array.isArray(artwork.images)
			? artwork.images.map((url, index) => ({
					url,
					isDefault: index === 0,
					caption: artwork.title,
				}))
			: [];
		const collection = artwork.collectionSlug
			? collectionsBySlug.get(artwork.collectionSlug) ?? null
			: null;

		return {
			title: artwork.title,
			slug: artwork.slug,
			description: artwork.description ?? null,
			artist: artwork.artist ?? null,
			year: artwork.year ?? null,
			publishedAt: artwork.publishedAt,
			locale: artwork.locale ?? "en",
			images,
			defaultImageUrl: images[0]?.url ?? null,
			collections: collection ? [collection] : [],
		};
	});

const artworksBySlug = new Map(artworks.map((artwork) => [artwork.slug, artwork]));

const products = productFixtures
	.map((product) => {
		const artwork = product.artworkSlug
			? artworksBySlug.get(product.artworkSlug) ?? null
			: null;

		if (product.artworkSlug && !artwork) {
			return null;
		}

		const slug = product.slug ?? product.artworkSlug ?? null;
		const name = product.name ?? artwork?.title ?? null;

		if (!slug || !name) {
			return null;
		}

		return {
			type: product.type,
			artworkSlug: product.artworkSlug ?? null,
			name,
			slug,
			description: product.description ?? null,
			imageUrl: product.imageUrl ?? artwork?.defaultImageUrl ?? null,
			price: product.price,
			quantity: product.quantity ?? null,
		};
	})
	.filter(Boolean);

const homepage = homepageSlugs
	.map((slug) => artworksBySlug.get(slug) ?? null)
	.filter(Boolean);

const generatedModule = `// Generated by code/scripts/sync-static-catalog.mjs. Do not edit by hand.
export default ${JSON.stringify(
	{
		collections: publishedCollections,
		artworks,
		products,
		homepage,
	},
	null,
	2,
)};
`;

await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, generatedModule, "utf8");

console.log(`Synced static catalog to ${path.relative(codeRoot, outputFile)}`);
